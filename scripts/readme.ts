import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { dumpsys } from './content';
import { OUTPUT_BASE, layout, type Cell } from './layout';

function picture(base: string, c: Cell): string {
  const img = [
    '<picture>',
    `<source media="(prefers-color-scheme: dark)" srcset="${base}dark/${c.file}">`,
    `<source media="(prefers-color-scheme: light)" srcset="${base}light/${c.file}">`,
    `<img src="${base}dark/${c.file}" width="${c.width}" alt="${c.alt.replace(/"/g, '&quot;')}">`,
    '</picture>',
  ].join('');
  return c.link ? `<a href="${c.link}">${img}</a>` : img;
}

export function renderReadme(base: string): string {
  const parts = layout.map((block) => {
    if (block.kind === 'dumpsys') {
      return `<details>
<summary><code>$ adb shell dumpsys endlessYoung</code></summary>

\`\`\`
${dumpsys}
\`\`\`

</details>`;
    }
    return `<p align="center">\n${block.cells.map((c) => picture(base, c)).join('\n')}\n</p>`;
  });
  return `<!-- Generated by scripts/readme.ts. Edit scripts/content.ts or scripts/layout.ts instead. -->\n\n${parts.join('\n\n')}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile('README.md', renderReadme(OUTPUT_BASE));
  console.log('README.md written');
}
